"""Writes the constants of the node's audio front end (the resampler taps and the 106 sparse mel bands) as a C header, and a header of test windows with the reference patches, from src/frontend_ref.py
and the vectors saved by frontend_check.py (runs_cloud/n1024/vectors.npz).  Run: .venv/bin/python scripts/50_frontend_header.py"""
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE / "src"))
import frontend_ref as R

v = np.load(HERE / "runs_cloud" / "n1024" / "vectors.npz"); taps = v["taps"].astype(np.float32)
mb = R.kaldi_mel_banks()[:R.N_BANDS]
starts, counts, flat = [], [], []
for row in mb:
    nz = np.nonzero(row)[0]; starts.append(int(nz[0])); counts.append(int(nz[-1] - nz[0] + 1)); flat += [float(x) for x in row[nz[0]:nz[-1] + 1]]
arr = lambda name, a, t="float": f"static const {t} {name}[] = {{" + ",".join(f"{x:.9g}f" if t == "float" else str(x) for x in a) + "};\n"
dest = HERE.parent / "node-firmware" / "lib" / "Acoustic" / "src" / "MelConstants.h"
with open(dest, "w") as f:
    f.write("#pragma once\n// Generated by acoustic-ml/scripts/50_frontend_header.py from frontend_ref.py: do not edit.\n// The audio front end the int8 mn10_as was trained on (see frontend_ref.py for the steps).\n#include <cstdint>\nnamespace terrawatch::acoustic::mel {\n")
    f.write(f"static const int kInputRate = {R.SR_IN}, kFftSize = {R.N_FFT}, kWindow = {R.WIN}, kHop = {R.HOP}, kBands = {R.N_BANDS}, kTaps = {taps.shape[1]};\n")
    f.write("// Polyphase taps of the 16 kHz -> 32 kHz resampler: y[2n + p] = sum_k kResampleTaps[p][k] * x[n + k - kTaps / 2].\n" + arr("kResampleTaps", taps.reshape(-1)))
    f.write("// Mel band b weighs FFT bins kBandStart[b] .. kBandStart[b] + kBandCount[b] - 1 with kBandWeights[kBandOffset[b] ...].\n" + arr("kBandStart", starts, "uint16_t") + arr("kBandCount", counts, "uint16_t") + arr("kBandOffset", np.concatenate([[0], np.cumsum(counts)[:-1]]).tolist(), "uint16_t") + arr("kBandWeights", flat) + "}\n")
print("constants:", dest, "bands", len(starts), "weights", len(flat), "max bin used", max(s + c for s, c in zip(starts, counts)))
# test windows: int16 as the microphone gives, reference computed in float64 from exactly those samples
w16 = v["wav_int16"]; pick = [0, 5, 10, 15, 20, 25, 30, 35]
exp = np.stack([R.log_mel(w16[i].astype(np.float64) / 32768.0, v["taps"]) for i in pick]).astype(np.float32)
dest2 = HERE / "board-bench" / "src" / "frontend_vectors.h"
with open(dest2, "w") as f:
    f.write("// generated by scripts/50_frontend_header.py: do not edit\n#pragma once\n#include <cstdint>\nstatic const int kNVectors = %d;\n" % len(pick))
    f.write("static const int16_t kVecPcm[%d][16000] = {" % len(pick) + ",".join("{" + ",".join(str(int(x)) for x in w16[i]) + "}" for i in pick) + "};\n")
    f.write("static const float kVecPatch[%d][%d] = {" % (len(pick), R.N_BANDS * 100) + ",".join("{" + ",".join(f"{x:.7g}f" for x in e.reshape(-1)) + "}" for e in exp) + "};\n")
print("test vectors:", dest2, exp.shape, "rms of the windows", [round(float(np.sqrt(((w16[i] / 32768.0) ** 2).mean())), 4) for i in pick])
