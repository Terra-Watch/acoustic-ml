"""Three dummy int8 classifiers (factorized inverted-residual style, no dense layers) sized to about 5, 30 and 100 M MACs for the ESP32-S3 speed test.
Input 1x40x101x1 int8, output 1x6 int8. Random weights (only the speed matters). Per-tensor quantization (the stock TFLM FULLY_CONNECTED mishandles per-channel weights).
Writes models/<name>.tflite and src/models_data.h. Run: /Users/kireeti/Desktop/Projects/SECURE-FOREST-PATROL/ml/venv/bin/python -I build_models.py"""
import os
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"
import json
from pathlib import Path

import numpy as np
import tensorflow as tf

HERE = Path(__file__).resolve().parent
L = tf.keras.layers
STAGES = [(1, 2, 1), (2, 2, 2), (4, 3, 2), (8, 2, 2)]   # (channel multiple, blocks, stride of the first block)
EXPAND = 3


def build(c):
    x = inp = tf.keras.Input((40, 101, 1), batch_size=1)
    x = L.Conv2D(c, 3, padding="same", activation="relu6")(x)
    ch = c
    for mult, n, stride in STAGES:
        out = c * mult
        for b in range(n):
            s = stride if b == 0 else 1
            y = L.Conv2D(ch * EXPAND, 1, activation="relu6")(x)
            y = L.DepthwiseConv2D(3, strides=s, padding="same", activation="relu6")(y)
            y = L.Conv2D(out, 1)(y)
            x = L.Add()([x, y]) if (s == 1 and ch == out) else y
            ch = out
    x = L.GlobalAveragePooling2D(keepdims=True)(x)
    x = L.Conv2D(6, 1)(x)
    x = L.Lambda(lambda t: tf.reshape(t, (1, 6)))(x)   # static shape: Reshape((6,)) adds SHAPE/PACK/STRIDED_SLICE ops
    return tf.keras.Model(inp, x)


def macs_params(model):
    macs = 0
    for l in model.layers:
        if isinstance(l, L.DepthwiseConv2D):
            h, w, c = l.output.shape[1:]; macs += h * w * c * l.kernel_size[0] * l.kernel_size[1]
        elif isinstance(l, L.Conv2D):
            h, w, co = l.output.shape[1:]; macs += h * w * co * l.kernel_size[0] * l.kernel_size[1] * l.input.shape[-1]
    return macs, model.count_params()


def fit(target):
    lo, hi = 2, 400
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if macs_params(build(mid))[0] < target: lo = mid
        else: hi = mid
    return lo


def convert(model, seed):
    rng = np.random.default_rng(seed)
    rep = lambda: ((rng.random((1, 40, 101, 1)).astype("float32") * 2 - 1) for _ in range(40))
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = lambda: ([x] for x in rep())
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8; conv.inference_output_type = tf.int8
    conv._experimental_disable_per_channel = True
    return conv.convert()


report = []
# m5/m30/m100 are fitted to a MAC target (odd channel counts); a8/a16 have channel counts that are multiples of 8 (the ESP-NN fast paths want that)
for name, target in (("m5", 5e6), ("m30", 30e6), ("m100", 100e6), ("a8", 8), ("a16", 16)):
    c = fit(target) if target > 100 else int(target); model = build(c)
    macs, params = macs_params(model)
    blob = convert(model, 1)
    (HERE / "models" / f"{name}.tflite").write_bytes(blob)
    it = tf.lite.Interpreter(model_content=blob); it.allocate_tensors()
    ops = sorted({d["op_name"] for d in it._get_ops_details()} - {"DELEGATE"})   # DELEGATE is the desktop XNNPACK wrapper
    i, o = it.get_input_details()[0], it.get_output_details()[0]
    it.set_tensor(i["index"], np.zeros(i["shape"], np.int8)); it.invoke()
    # any non-per-tensor weight quantization left?
    per_channel = any(len(d["quantization_parameters"]["scales"]) > 1 for d in it.get_tensor_details())
    report.append(dict(name=name, width=c, macs=macs, params=params, tflite_bytes=len(blob), ops=ops, input=str(i["dtype"].__name__) + str(list(i["shape"])), output=str(o["dtype"].__name__) + str(list(o["shape"])), per_channel_tensors=per_channel))
    print(report[-1], flush=True)
(HERE / "models" / "report.json").write_text(json.dumps(report, indent=1))

with open(HERE / "src" / "models_data.h", "w") as f:
    f.write("// generated by build_models.py: do not edit\n#pragma once\n#include <cstddef>\n")
    for r in report:
        b = (HERE / "models" / f"{r['name']}.tflite").read_bytes()
        f.write(f"alignas(16) const unsigned char model_{r['name']}[] = {{" + ",".join(str(x) for x in b) + "};\n")
        f.write(f"const size_t model_{r['name']}_len = {len(b)};\n")
