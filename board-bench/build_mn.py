"""Timing proxies of the EfficientAT MobileNetV3 models (mn10_as = width 1.0, mn04_as = width 0.4) for the ESP32-S3 speed test: the Keras MobileNetV3-Large with the same width multiplier,
input 1 x 128 mel bands x 100 frames x 1 (one second of audio as the fine-tuned models take it), int8, per-tensor, random weights. Only the speed matters (the layer shapes and op types decide it);
the accuracy of an int8 conversion of the trained weights is a separate test.
Writes models/<name>.tflite and src/models_mn.h. Run: /Users/kireeti/Desktop/Projects/SECURE-FOREST-PATROL/ml/venv/bin/python -I build_mn.py"""
import os
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"
import json
from pathlib import Path

import numpy as np
import tensorflow as tf

HERE = Path(__file__).resolve().parent
L = tf.keras.layers


def build(alpha):
    base = tf.keras.applications.MobileNetV3Large(input_shape=(128, 100, 1), alpha=alpha, include_top=False, weights=None, include_preprocessing=False)
    x = L.GlobalAveragePooling2D(keepdims=True)(base.output)
    x = L.Conv2D(6, 1)(x)
    x = L.Lambda(lambda t: tf.reshape(t, (1, 6)))(x)
    inp = tf.keras.Input((128, 100, 1), batch_size=1)
    return tf.keras.Model(inp, tf.keras.Model(base.input, x)(inp))


def macs(model):
    total = 0
    def walk(m):
        nonlocal total
        for l in m.layers:
            if isinstance(l, tf.keras.Model): walk(l)
            elif isinstance(l, L.DepthwiseConv2D): h, w, c = l.output.shape[1:]; total += h * w * c * l.kernel_size[0] * l.kernel_size[1]
            elif isinstance(l, L.Conv2D): h, w, co = l.output.shape[1:]; total += h * w * co * l.kernel_size[0] * l.kernel_size[1] * l.input.shape[-1]
    walk(model); return total


def convert(model):
    rng = np.random.default_rng(1)
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = lambda: ([rng.random((1, 128, 100, 1)).astype("float32") * 2 - 1] for _ in range(30))
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8; conv.inference_output_type = tf.int8
    conv._experimental_disable_per_channel = True
    return conv.convert()


report = []
for name, alpha in (("mn10p", 1.0), ("mn04p", 0.4)):
    model = build(alpha); blob = convert(model); (HERE / "models" / f"{name}.tflite").write_bytes(blob)
    it = tf.lite.Interpreter(model_content=blob); it.allocate_tensors()
    ops = sorted({d["op_name"] for d in it._get_ops_details()} - {"DELEGATE"})
    i = it.get_input_details()[0]; it.set_tensor(i["index"], np.zeros(i["shape"], np.int8)); it.invoke()
    report.append(dict(name=name, alpha=alpha, macs=int(macs(model)), params=int(model.count_params()), tflite_bytes=len(blob), ops=ops, input=[int(v) for v in i["shape"]]))
    print(report[-1], flush=True)
(HERE / "models" / "report_mn.json").write_text(json.dumps(report, indent=1))
with open(HERE / "src" / "models_mn.h", "w") as f:
    f.write("// generated by build_mn.py: do not edit\n#pragma once\n#include <cstddef>\n")
    for r in report:
        b = (HERE / "models" / f"{r['name']}.tflite").read_bytes()
        f.write(f"alignas(16) const unsigned char model_{r['name']}[] = {{" + ",".join(str(x) for x in b) + "};\n")
        f.write(f"const size_t model_{r['name']}_len = {len(b)};\n")
