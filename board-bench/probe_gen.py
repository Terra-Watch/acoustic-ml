"""Finds where the board's int8 results leave the computer's: for every operation output of a model, the reference value (sum and first 8 values on the fixed test input) is computed with the TFLite reference kernels,
and the position of the graph-output entry in the model file is found, so the firmware can patch it to read any tensor. Writes src/probe_data.h and probe_expected.json.
Run: /Users/kireeti/Desktop/Projects/SECURE-FOREST-PATROL/ml/venv/bin/python -I probe_gen.py mn10real_pc"""
import json, os, sys
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"
from pathlib import Path

import numpy as np
import tensorflow as tf
from tensorflow.lite.python import schema_py_generated as S

name = sys.argv[1]; path = Path(__file__).parent / "models" / f"{name}.tflite"
buf = bytearray(path.read_bytes())
model = S.Model.GetRootAsModel(buf, 0); sg = model.Subgraphs(0)
tab = sg._tab; o = tab.Offset(8)                      # SubGraph field 2 = outputs
pos = tab.Vector(o); n_out = tab.VectorLen(o); assert n_out == 1, n_out
cur = int.from_bytes(buf[pos:pos + 4], "little"); print("outputs vector at byte", pos, "holds tensor", cur)

it = tf.lite.Interpreter(model_path=str(path), experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES, experimental_preserve_all_tensors=True)
it.allocate_tensors(); i = it.get_input_details()[0]
x = np.array([((k * 37) % 255 - 127) for k in range(int(np.prod(i["shape"])))], np.int8).reshape(i["shape"]); it.set_tensor(i["index"], x); it.invoke()
probes, exp = [], []
for op in it._get_ops_details():
    for t in op["outputs"]:
        d = it.get_tensor_details()[t]
        if d["dtype"] != np.int8: continue
        a = it.get_tensor(t).reshape(-1)
        probes.append(int(t)); exp.append(dict(tensor=int(t), op=op["op_name"], n=int(a.size), sum=int(a.astype(np.int64).sum()), first8=[int(v) for v in a[:8]]))
Path(__file__).with_name("probe_expected.json").write_text(json.dumps(exp))
with open(Path(__file__).parent / "src" / "probe_data.h", "w") as f:
    f.write(f"// generated by probe_gen.py for {name}\n#pragma once\n#include <cstddef>\n#include <cstdint>\nconst size_t kOutPos = {pos};\nconst int kNProbes = {len(probes)};\nconst int kProbes[] = {{{','.join(map(str, probes))}}};\n")
print(len(probes), "probes")
